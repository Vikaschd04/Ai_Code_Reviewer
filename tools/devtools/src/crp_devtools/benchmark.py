"""``crp-dev benchmark``: time and memory of real scans on a generated, labelled medium fixture.

Starts a throwaway PostgreSQL, Temporal dev server, API and worker (no web), uploads a
deterministic synthetic project through the HTTP API, runs a cold scan and a warm (cache) scan,
samples the worker process tree's resident memory, and times bounded read APIs. Results go to
``.local/benchmarks/``. This measures one machine and one fixture; it is not a scale claim.
"""

