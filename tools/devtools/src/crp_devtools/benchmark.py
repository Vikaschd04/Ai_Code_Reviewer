FIXTURE_LABEL = "synthetic-medium-v1"


def generate_medium_fixture(
    java_modules: int = 4,
    java_per_module: int = 150,
    ts_packages: int = 2,
    ts_per_package: int = 200,
) -> bytes:
    """Deterministic multi-module Java + TypeScript project as a ZIP (synthetic, no secrets)."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(
            "README.md",
            f"# {FIXTURE_LABEL}\n\nGenerated by `crp-dev benchmark`; synthetic code only.\n",
        )
        modules = "".join(f"    <module>m{m}</module>\n" for m in range(java_modules))
        zf.writestr(
            "pom.xml",
            '<?xml version="1.0"?>\n<project xmlns="http://maven.apache.org/POM/4.0.0">\n'
            "  <modelVersion>4.0.0</modelVersion>\n  <groupId>org.bench</groupId>\n"
            "  <artifactId>root</artifactId>\n  <version>1</version>\n"
            "  <packaging>pom</packaging>\n"
            f"  <modules>\n{modules}  </modules>\n</project>\n",
        )
        for m in range(java_modules):
            dep = (
                f"    <dependency><groupId>org.bench</groupId><artifactId>m{m - 1}</artifactId>"
                "<version>1</version></dependency>\n"
                if m
                else ""
            )
            zf.writestr(
                f"m{m}/pom.xml",
                '<?xml version="1.0"?>\n<project xmlns="http://maven.apache.org/POM/4.0.0">\n'
                "  <modelVersion>4.0.0</modelVersion>\n"
                "  <parent><groupId>org.bench</groupId><artifactId>root</artifactId>"
                "<version>1</version></parent>\n"
                f"  <artifactId>m{m}</artifactId>\n  <dependencies>\n{dep}  </dependencies>\n"
                "</project>\n",
            )
            for i in range(java_per_module):
                imports = []
                if i:
                    imports.append(f"import org.bench.m{m}.Service{i - 1};")
                if m and i % 5 == 0:
                    imports.append(f"import org.bench.m{m - 1}.Service{i};")
                imports.append("import java.util.List;")
                parent = f" extends Service{i - 1}" if i and i % 7 == 0 else ""
                body = "\n".join(
                    f"    public int compute{k}(int value) {{\n"
                    f"        int result = value * {k + 1};\n"
                    f"        if (result > {k * 10}) {{\n            result -= {k};\n        }}\n"
                    "        return result;\n    }\n"
                    for k in range(8)
                )
                defect = (
                    "    public boolean isPaid(String status) {\n"
                    '        return status == "PAID";\n    }\n'
                    if i % 10 == 0
                    else ""
                )
                zf.writestr(
                    f"m{m}/src/main/java/org/bench/m{m}/Service{i}.java",
                    f"package org.bench.m{m};\n\n" + "\n".join(imports) + "\n\n"
                    f"public class Service{i}{parent} {{\n{body}{defect}"
                    "    public List<String> names() {\n        return List.of();\n    }\n}\n",
                )
        for p in range(ts_packages):
            deps = {"@bench/p0": "workspace:*"} if p else {}
            zf.writestr(
                f"web{p}/package.json",
                json.dumps({"name": f"@bench/p{p}", "version": "1.0.0", "dependencies": deps}),
            )
            zf.writestr(
                f"web{p}/tsconfig.json",
                '{\n  // synthetic\n  "compilerOptions": '
                '{"baseUrl": ".", "paths": {"@/*": ["src/*"]}}\n}\n',
            )
            for i in range(ts_per_package):
                imports = [f'import {{ value{i - 1} }} from "./module{i - 1}";'] if i else []
                if i % 9 == 0 and i:
                    imports.append(f'import {{ value{i // 2} }} from "@/module{i // 2}";')
                if p and i % 20 == 0:
                    imports.append('import { value0 as shared } from "@bench/p0";')
                defect = "  if (input == 1) { debugger; }\n" if i % 10 == 0 else ""
                functions = "\n".join(
                    f"export function helper{i}_{k}(input: number): number {{\n"
                    f"  const scaled = input * {k + 2};\n"
                    f"  return scaled > {k} ? scaled - {k} : scaled;\n}}\n"
                    for k in range(6)
                )
                zf.writestr(
                    f"web{p}/src/module{i}.ts",
                    "\n".join(imports)
                    + ("\n\n" if imports else "")
                    + f"export const value{i} = {i};\n\n"
                    + f"export function run{i}(input: number): number {{\n"
                    + defect
                    + f"  return input + value{i};\n}}\n\n{functions}",
                )
    return buffer.getvalue()


@dataclass
class TreeSampler:
    """Samples the summed RSS of a process and its descendants (via ``ps``)."""

    pid: int
    interval: float = 0.25
    peak_kb: int = 0
    _stop: threading.Event = field(default_factory=threading.Event)
    _thread: threading.Thread | None = None

    def _sample(self) -> int:
        output = subprocess.run(
            ["/bin/ps", "-A", "-o", "pid=,ppid=,rss="], capture_output=True, text=True, check=False
        ).stdout
        children: dict[int, list[int]] = {}
        rss: dict[int, int] = {}
        for line in output.splitlines():
            parts = line.split()
            if len(parts) == 3 and all(p.isdigit() for p in parts):
                pid, ppid, kb = map(int, parts)
                children.setdefault(ppid, []).append(pid)
                rss[pid] = kb
        total, stack = 0, [self.pid]
        while stack:
            current = stack.pop()
            total += rss.get(current, 0)
            stack.extend(children.get(current, []))
        return total

    def __enter__(self) -> TreeSampler:
        self.peak_kb = 0

        def loop() -> None:
            while not self._stop.is_set():
                self.peak_kb = max(self.peak_kb, self._sample())
                self._stop.wait(self.interval)

        self._stop.clear()
        self._thread = threading.Thread(target=loop, daemon=True)
        self._thread.start()
        return self

    def __exit__(self, *_: object) -> None:
        self._stop.set()
        if self._thread is not None:
            self._thread.join()


def _ok(response: httpx.Response) -> Any:
    if not response.is_success:
        raise RuntimeError(f"{response.request.method} {response.request.url}: {response.text}")
    return response.json() if response.content else None


def _wait(client: httpx.Client, path: str, done: set[str], limit: float = 1800) -> dict[str, Any]:
    deadline = time.monotonic() + limit
    while time.monotonic() < deadline:
        body: dict[str, Any] = _ok(client.get(path))
        if body["state"] in done:
            return body
        time.sleep(0.5)
    raise RuntimeError(f"timed out waiting for {path}")


def _timed(client: httpx.Client, path: str) -> float:
    started = time.perf_counter()
    _ok(client.get(path))
    return round((time.perf_counter() - started) * 1000, 1)


def _scan(
    client: httpx.Client, project: str, snapshot: str, sampler: TreeSampler
) -> dict[str, Any]:
    started = time.perf_counter()
    with sampler:
        scan = _ok(client.post(f"/v1/projects/{project}/scans", json={"snapshot_id": snapshot}))
        done = _wait(
            client, f"/v1/scans/{scan['id']}", {"SUCCEEDED", "PARTIAL", "FAILED", "CANCELED"}
        )
    return {
        "scan_id": done["id"],
        "state": done["state"],
        "wall_seconds": round(time.perf_counter() - started, 2),
        "worker_tree_peak_rss_mb": round(sampler.peak_kb / 1024, 1),
        "findings": done["summary"]["findings"],
        "engines": {
            e["engine"]: {
                "state": e["state"],
                "eligible": e["files_eligible"],
                "duration_ms": e["duration_ms"],
                "cache_hits": e["cache_hits"],
                "cache_misses": e["cache_misses"],
                "findings": e["findings_count"],
            }
            for e in done["engines"]
        },
    }


def run_benchmark(paths: DevPaths, *, java_per_module: int, ts_per_package: int) -> Path:
    work = Path(tempfile.mkdtemp(prefix="crp-bench-"))
    cluster = PostgresCluster(
        data_dir=work / "pg", port=free_port(), password=generate_token(), log_file=work / "pg.log"
    )
    temporal = TemporalDevServer(port=free_port(), log_file=work / "temporal.log")
    supervisor = Supervisor(echo=False)
    try:
        cluster.init()
        cluster.start()
        cluster.create_database(DATABASE_NAME)
        temporal.start(detach=False)
        token_file = work / "token"
        write_secret_file(token_file, generate_token())
        api_port = free_port()
        env = service_env(
            repo=paths.repo,
            token_file=token_file,
            database_url=cluster.url(DATABASE_NAME),
            temporal_address=temporal.address,
            api_port=api_port,
            web_origins=(f"http://{LOOPBACK}:{free_port()}",),
            artifacts=work / "artifacts",
            work_root=work / "scan-work",
            log_format="json",
        )
        migrate_and_provision(settings_from_env(env))
        full_env = child_env(env)
        supervisor.start(
            ServiceSpec(
                "api", [sys.executable, "-m", "crp_api"], full_env, paths.repo, work / "api.log"
            )
        )
        worker = supervisor.start(
            ServiceSpec(
                "worker",
                [sys.executable, "-m", "crp_worker"],
                full_env,
                paths.repo,
                work / "worker.log",
            )
        )
        wait_http(f"http://{LOOPBACK}:{api_port}/v1/health/live", 60)
        archive = generate_medium_fixture(
            java_per_module=java_per_module, ts_per_package=ts_per_package
        )
        token = token_file.read_text().strip()
        headers = {"Authorization": f"Bearer {token}"}
        with httpx.Client(
            base_url=f"http://{LOOPBACK}:{api_port}", headers=headers, timeout=120
        ) as client:
            workspace = _ok(client.get("/v1/auth/me"))["workspaces"][0]["workspace_id"]
            project = _ok(
                client.post("/v1/projects", json={"workspace_id": workspace, "name": "Benchmark"})
            )["id"]
            started = time.perf_counter()
            intake = _ok(
                client.post(
                    f"/v1/projects/{project}/intakes",
                    json={"mode": "zip_upload", "display_name": f"{FIXTURE_LABEL}.zip"},
                )
            )
            _ok(
                client.put(
                    f"/v1/intakes/{intake['id']}/content",
                    content=archive,
                    headers={"Content-Type": "application/zip"},
                )
            )
            _ok(client.post(f"/v1/intakes/{intake['id']}/finalize"))
            ready = _wait(client, f"/v1/intakes/{intake['id']}", {"READY", "REJECTED", "FAILED"})
            intake_seconds = round(time.perf_counter() - started, 2)
            snapshot_id = ready["snapshot_id"]
            snapshot = _ok(client.get(f"/v1/snapshots/{snapshot_id}"))
            sampler = TreeSampler(worker.pid)
            cold = _scan(client, project, snapshot_id, sampler)
            warm = _scan(client, project, snapshot_id, sampler)
            graph = _ok(client.get(f"/v1/snapshots/{snapshot_id}/graph"))
            node = _ok(
                client.get(f"/v1/snapshots/{snapshot_id}/graph/nodes?q=Service0.java&kind=file")
            )["items"][0]
            base = f"/v1/snapshots/{snapshot_id}/graph"
            latency = {
                "findings_page_ms": _timed(
                    client, f"/v1/scans/{warm['scan_id']}/findings?limit=50"
                ),
                "issues_page_ms": _timed(client, f"/v1/projects/{project}/issues?limit=50"),
                "graph_summary_ms": _timed(client, base),
                "graph_search_ms": _timed(client, f"{base}/nodes?q=Service1&limit=25"),
                "neighborhood_depth2_ms": _timed(
                    client, f"{base}/nodes/{node['id']}/neighborhood?depth=2&limit=80"
                ),
                "impact_depth5_ms": _timed(
                    client, f"{base}/nodes/{node['id']}/impact?depth=5&limit=200"
                ),
                "compare_ms": _timed(
                    client, f"/v1/scans/{warm['scan_id']}/compare?base={cold['scan_id']}"
                ),
                "export_json_ms": _timed(client, f"/v1/scans/{warm['scan_id']}/export?format=json"),
                "export_sarif_ms": _timed(
                    client, f"/v1/scans/{warm['scan_id']}/export?format=sarif"
                ),
            }
        result = {
            "fixture": FIXTURE_LABEL,
            "generated_at": datetime.now(UTC).isoformat(),
            "machine": {
                "platform": platform.platform(),
                "processor": platform.processor() or platform.machine(),
                "python": platform.python_version(),
                "cpu_count": os.cpu_count(),
            },
            "snapshot": {
                "archive_bytes": len(archive),
                "files": snapshot["file_count"],
                "analyzable": snapshot["analyzable_count"],
                "total_bytes": snapshot["total_bytes"],
                "lines": sum(
                    item["lines"] for item in (snapshot["inventory"] or {}).get("languages", [])
                ),
            },
            "intake_seconds": intake_seconds,
            "cold_scan": cold,
            "warm_scan": warm,
            "graph": {
                "state": graph["build"]["state"],
                "nodes": graph["build"]["node_count"],
                "edges": graph["build"]["edge_count"],
                "unresolved": graph["build"]["unresolved_count"],
            },
            "api_latency_single_request": latency,
            "notes": [
                "One machine, one synthetic fixture, sequential requests; "
                "not a scale or SLO claim.",
                "Peak RSS sums the worker process and its engine child processes (ps sampling "
                "every 0.25 s; short spikes between samples can be missed).",
            ],
        }
        out_dir = paths.repo / ".local" / "benchmarks"
        out_dir.mkdir(parents=True, exist_ok=True)
        out = out_dir / f"p02-{datetime.now(UTC).strftime('%Y%m%dT%H%M%SZ')}.json"
        out.write_text(json.dumps(result, indent=2))
        return out
    finally:
        supervisor.stop_all()
        temporal.stop()
        cluster.stop()
        shutil.rmtree(work, ignore_errors=True)
